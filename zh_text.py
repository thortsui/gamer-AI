# OCR 常把這幾組互相看錯（只在最後一關的模糊比對用，不做硬替換）
LOOKALIKE = [
    {"戏", "戴", "戈", "载"},
    {"线", "综", "绵", "统"},
    {"闲", "间", "问", "闭"},
    {"断", "继", "斯"},
    {"开", "井", "并"},
    {"始", "姑", "妬"},
    {"离", "禽", "离"},
    {"录", "隶", "碌"},
]
_LOOK = {}
for grp in LOOKALIKE:
    for ch in grp:
        _LOOK.setdefault(ch, set()).update(grp)

_DROP = re.compile(r"[\s!！?？.。,，、:：;；'\"「」『』（）()\[\]【】<>《》~～\-—_+*/\\|#@$%^&]+")


def norm(s):
    """比對用的正規化：轉小寫、去標點空白、繁轉簡。"""
    s = str(s or "").strip().lower()
    s = _DROP.sub("", s)
    return "".join(T2S.get(ch, ch) for ch in s)


def _look_same(a, b):
    return a == b or b in _LOOK.get(a, ())


def similar(a, b):
    """0~1 的相似度：先用字元比對，再把形近字當成相同重算一次，取高的那個。"""
    a, b = norm(a), norm(b)
    if not a or not b:
        return 0.0
    base = difflib.SequenceMatcher(None, a, b).ratio()
    if len(a) == len(b):
        same = sum(1 for x, y in zip(a, b) if _look_same(x, y))
        base = max(base, same / len(a))
    return base


def find(want, texts, min_ratio=0.6):
    """在 texts（字串清單）裡找 want，回傳 [(index, 相似度, 怎麼中的)]，由高到低。

    三關：完全包含 → 正規化後包含 → 形近模糊比對。
    """
    w = str(want or "").strip()
    if not w:
        return []
    wl, wn = w.lower(), norm(w)
    out = []
    for i, t in enumerate(texts):
        s = str(t or "")
        if wl and wl in s.lower():
            out.append((i, 1.0, "完全符合"))
            continue
        tn = norm(s)
        if wn and tn and (wn in tn or tn in wn):
            out.append((i, 0.95, "繁簡／標點不同"))
            continue
        r = similar(wn, tn)
        if r >= min_ratio:
            out.append((i, round(r, 2), f"形近模糊比對 {r:.0%}"))
        elif len(wn) >= 2 and len(tn) >= 2:
            # 長句子裡含有短目標：逐段滑窗比一次（OCR 常把整列字連成一行）
            best = 0.0
            for j in range(0, max(1, len(tn) - len(wn) + 1)):
                best = max(best, similar(wn, tn[j:j + len(wn)]))
            if best >= min_ratio:
                out.append((i, round(best, 2), f"整行裡的一段 {best:.0%}"))
    out.sort(key=lambda x: -x[1])
    return out
