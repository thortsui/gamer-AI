def gen_find_numeric():
    out = []
    for _ in range(15):
        per = _rng.choice([4, 5, 6]); step = _rng.choice([100, 120, 150])
        deg = round(step / per)
        q = f"要原地掃一圈找東西，刻度每度 dx {per}。一次送 dx {step} 是幾度？要掃幾次？"
        a = f"{step} ÷ {per} ≈ {deg} 度一次，{'小於' if deg <= 25 else '約'}四分之一個畫面。360 ÷ {deg} ≈ {round(360/deg)} 次掃滿一圈；每次掃完停一下看清楚再掃，轉滿一圈還是沒有才換房間。"
        out.append((q, a))
    for _ in range(12):
        dirn, sec = _rng.choice([("左前方", 4.2), ("正後方", 8.7), ("右前方", 3.0), ("正右邊", 5.5), ("左後方", 6.1)])
        q = f"【你釘的標點】寫「📌 入口踏板：{dirn} {sec} 步」，這是現在看到的嗎？怎麼用？"
        a = f"不是，是推算出來的。用法只有一個動作：轉到{dirn}抬頭確認。真的在那個方向＝地圖是對的，放心照著走約 {sec} 秒；不在＝推算漂了，走到認得的標點旁送 {{\"t\":\"到標點\",\"name\":\"入口踏板\"}} 拉回座標。"
        out.append((q, a))
    for _ in range(10):
        n = _rng.choice([2, 3, 4, 5, 6, 8])
        q = f"【探索地圖】最後一行說最近的未探索 ？ 在你正前方 {n} 步，要找新東西怎麼走？"
        a = f"往 ？ 走：一格兩步，{{\"t\":\"key\",\"k\":\"w\",\"d\":{n}.0,\"g\":\"未探索區\"}}（程式會先走七成再問）。到了先環視、有新東西就釘標點、換一個區名。不要在走過的 · 裡繞。"
        out.append((q, a))
    return out


def build_A_app(chat):
    rows = []
    for series, hand, gen in (("互動", HAND_INTERACT, gen_interact_numeric),
                              ("緊急", HAND_EMERGENCY, gen_emergency_numeric),
                              ("找東西", HAND_FIND, gen_find_numeric)):
        for q, a in hand:
            rows.append(chat(SYS_APP, q, a, **{"class": "A_app", "系列": series, "型": "手寫"}))
        for q, a in gen():
            rows.append(chat(SYS_APP, q, a, **{"class": "A_app", "系列": series, "型": "數字"}))
    return rows


