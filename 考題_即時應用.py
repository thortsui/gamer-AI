def gen_interact_numeric():
    out = []
    # 偏角 → dx（刻度題目給）
    for _ in range(40):
        deg = _r(5, 60, 5); per = _rng.choice([3, 4, 5, 6, 8]); side = _rng.choice(["左", "右"])
        dx = deg * per * (-1 if side == "左" else 1)
        q = f"目標在畫面{side}邊，【對正提示】說差 {deg} 度；你量到的刻度是每度 dx {per}。這一輪送什麼？"
        a = (f"look：dx = {deg} × {per} = {abs(dx)}，{side}邊是{'負' if side == '左' else '正'}的 → "
             f"{{\"t\":\"look\",\"dx\":{dx},\"dy\":0}}。dy 沒事就填 0。"
             + ("程式會先轉七成再問剩下的兩成，過頭就答 false。" if abs(dx) >= 80 else "")
             + " 這一輪只轉不走，下一輪確認它在中央（x 0.45～0.55）再走。")
        out.append((q, a))
    # 俯仰 → dy（規則：N × 3.4，抬頭送正、低頭送負）
    for _ in range(30):
        n = _r(10, 89, 1); up = _rng.choice([True, False])
        dy = int(round(n * 3.4)) * (1 if up else -1)
        q = f"水平儀說你{'抬頭' if up else '低頭'} {n} 度，要先修回水平才能對準目標。dy 送多少？"
        a = (f"dy = {n} × 3.4 ≈ {abs(dy)}，{'偏上用正的 dy 往下修' if up else '偏下用負的 dy 往上修'} → "
             f"{{\"t\":\"look\",\"dx\":0,\"dy\":{dy}}}。一次送完，不要分五次慢慢磨；修完下一輪先看度數回到水平了沒，再對準、再走。")
        out.append((q, a))
    # 框高 → 秒數
    for _ in range(40):
        h = _rng.choice([0.08, 0.10, 0.12, 0.15, 0.18, 0.20, 0.25, 0.30, 0.35, 0.40]); k = _rng.choice([0.2, 0.25, 0.3, 0.4, 0.5])
        sec = (1 / h - 1 / 0.55) * k
        sec_r = round(sec, 1)
        q = f"目標在畫面中央，框高 {h}，你走出來的 k 是 {k}。要走幾秒？怎麼送？"
        a = (f"秒數 ≈ (1/{h} − 1/0.55) × {k} = ({1/h:.2f} − 1.82) × {k} ≈ {sec_r} 秒 → "
             f"{{\"t\":\"key\",\"k\":\"w\",\"d\":{sec_r},\"g\":\"目標\"}}，一次走完不要拆成好幾次 0.5 秒。"
             + (f"0.6 秒以上程式會先走七成（{round(sec_r*0.7,1)} 秒）再問剩下的。" if sec_r >= 0.6 else "")
             + " 走完看它有沒有變大：變大＝走對了。框高到 0.55 左右就是到它面前了，看 E 提示再按。")
        out.append((q, a))
    # 綜合：偏角＋框高 → 兩輪
    for _ in range(30):
        deg = _r(10, 45, 5); per = _rng.choice([4, 5, 6]); side = _rng.choice(["左", "右"])
        h = _rng.choice([0.12, 0.15, 0.20, 0.25, 0.30]); k = _rng.choice([0.25, 0.3, 0.4])
        dx = deg * per * (-1 if side == "左" else 1); sec_r = round((1 / h - 1 / 0.55) * k, 1)
        q = f"要互動的機台在{side}前方，差 {deg} 度，框高 {h}；刻度每度 dx {per}、k {k}。接下來兩輪各送什麼？"
        a = (f"第一輪只對正：dx = {deg} × {per} = {abs(dx)} → {{\"t\":\"look\",\"dx\":{dx},\"dy\":0}}。\n"
             f"第二輪確認它在中央後走：秒數 ≈ (1/{h} − 1/0.55) × {k} ≈ {sec_r} → {{\"t\":\"key\",\"k\":\"w\",\"d\":{sec_r},\"g\":\"機台\"}}。\n"
             f"到了之後（框高約 0.55、程式說已到面前）看 E 提示再 {{\"t\":\"hold\",\"k\":\"e\",\"g\":\"機台\"}}。面對與移動分兩步，同輪兼具時移動會被拿掉。")
        out.append((q, a))
    # 拆兩段
    for _ in range(20):
        want = _rng.choice([1.0, 1.5, 2.0, 2.5, 3.0, 4.0]); seven = round(want * 0.7, 1); two = round(want * 0.2, 1)
        q = f"你送了 w {want} 秒，程式會怎麼替你走？你要怎麼答？"
        a = (f"先走七成＝{seven} 秒，停下來抓畫面：①畫面沒變＝被擋住，後面兩成不走；②有變就問你剩下的兩成（{two} 秒）還要不要走。"
             f"目標到了、已對正、再走會撞到或過頭就答 false；還差一點、前面是空的才答 true。兩段合計最多九成，永遠不會超過你要的量。")
        out.append((q, a))
    for _ in range(15):
        dx = _rng.choice([80, 100, 120, 150, 200, 250]); sign = _rng.choice([1, -1]); seven = int(dx * 0.7)
        q = f"你送了 look dx {dx*sign}，程式會怎麼替你轉？什麼時候答 false？"
        a = (f"dx 80 以上程式先替你轉七成＝{seven*sign}，抓一張畫面問剩下的兩成要不要轉。已經對正、目標在畫面中間、再轉會過頭就答 false；差一點下一輪再補。合計最多九成。")
        out.append((q, a))
    # 點座標
    for _ in range(15):
        x = round(_rng.uniform(0.2, 0.8), 2); y = round(_rng.uniform(0.2, 0.8), 2)
        pos = ("左" if x < 0.4 else "右" if x > 0.6 else "中") + ("上" if y < 0.4 else "下" if y > 0.6 else "中")
        q = f"OCR 說按鈕「確認」的框中心在 ({x},{y})，在畫面{pos}。要怎麼點？"
        a = (f"直接 {{\"t\":\"點字\",\"字\":\"確認\"}}，程式用當下 OCR 的框中心去點；或 {{\"t\":\"click\",\"x\":{x},\"y\":{y},\"g\":\"確認\"}}（x、y 是畫面比例，左上角 0,0）。點完看畫面有沒有變，沒變就往旁邊挪一點再點。")
        out.append((q, a))
    return out


