def _load_reviews(here):
    rows = []
    for g in ("動物醫院", "新遊戲"):
        for f in ("卡住檢討", "卡牆檢討", "走過頭檢討", "死亡檢討", "放棄檢討"):
            p = os.path.join(here, "專案", g, "記憶", f + ".md")
            if not os.path.exists(p):
                continue
            s = io.open(p, encoding="utf-8").read()
            for blk in re.split(r"\n(?=## )", s):
                m = re.match(r"## (\S+ \S+) (.*)", blk)
                if not m:
                    continue
                d = {"game": g, "src": f, "題": m.group(2).strip()}
                for line in blk.splitlines()[1:]:
                    mm = re.match(r"- (.+?)：(.*)", line)
                    if mm:
                        d[mm.group(1)] = mm.group(2).strip()
                rows.append(d)
    return rows


def _classify(text):
    hits = [k for k, (r, _, _) in PAT.items() if re.search(r, text)]
    return hits


def build_A_stuck(chat, mask, has_game_word, here, per_pattern=9):
    rows = []
    # ① 每一種卡法：用他的話問、答解法
    for k, (r, desc, ans) in PAT.items():
        rows.append(chat(SYS_STUCK, f"你自己整理過：你常常{desc}。怎麼解決？", ans, **{"class": "A_stuck", "卡法": k, "型": "總結"}))
        rows.append(chat(SYS_STUCK, f"你卡住了，自己寫的檢討是「{desc}」。下次怎麼做？", ans, **{"class": "A_stuck", "卡法": k, "型": "總結"}))
    # ② 他的檢討實例：原因＋錯在哪 → 解法（遮遊戲名詞，遮太多的不要）
    reviews = _load_reviews(here)
    by = {k: [] for k in PAT}
    for d in reviews:
        cause = d.get("原因", "") or d.get("死因", "")
        wrong = d.get("錯在哪", "") or d.get("錯誤決定", "")
        if len(cause) < 8 and len(wrong) < 8:
            continue
        hits = _classify(cause + "｜" + wrong)
        if not hits:
            continue
        q_cause, q_wrong = mask(cause), mask(wrong)
        if (q_cause + q_wrong).count("某物") > 2 or has_game_word(q_cause + q_wrong):
            continue
        for k in hits[:2]:
            by[k].append((q_cause, q_wrong, hits[:2], d["src"]))
    for k, lst in by.items():
        _rng.shuffle(lst)
        for q_cause, q_wrong, hits, src in lst[:per_pattern]:
            q = "你卡住了。原因：" + q_cause + ("｜錯在哪：" + q_wrong if q_wrong else "") + "。怎麼解決？"
            if len(hits) == 1:
                a = PAT[hits[0]][2]
            else:
                a = "①" + PAT[hits[0]][2] + "\n②" + PAT[hits[1]][2]
            rows.append(chat(SYS_STUCK, q, a, **{"class": "A_stuck", "卡法": k, "型": "實例", "來源": src}))
    # ③ 他自己訂的扣分規則：被扣什麼、他寫的原因 → 正確解法
    for g in ("動物醫院", "新遊戲"):
        p = os.path.join(here, "專案", g, "記憶", "扣分檢討.json")
        if not os.path.exists(p):
            continue
        for name, v in json.load(io.open(p, encoding="utf-8")).items():
            k = PENALTY_MAP.get(name)
            if not k:
                continue
            why = mask(v.get("為什麼", ""))
            if not why or why.count("某物") > 2 or has_game_word(why):
                continue
            q = f"你被扣「{name}」，你自己寫的原因是：{why}。正確的做法是什麼？"
            rows.append(chat(SYS_STUCK, q, PAT[k][2], **{"class": "A_stuck", "卡法": k, "型": "扣分"}))
    return rows


